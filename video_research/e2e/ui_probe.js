// Böngészős (Chromium, Playwright) működési próba: terv -> jóváhagyás -> feldolgozás -> jelentés -> bizonyítékok -> visszajelzés.
// Előfeltétel: a probe_server fut (python -m video_research.e2e.probe_server 8765). Futtatás: node ui_probe.js [port] [kimeneti-mappa]
const { chromium } = require("playwright");
const port = process.argv[2] || "8765", out = process.argv[3] || ".";
const log = [], fail = [];
const step = (n, ok, info) => { log.push(`${ok ? "OK  " : "HIBA"} ${n}${info ? " — " + info : ""}`); if (!ok) fail.push(n); };
(async () => {
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 1000, height: 1400 } });
  const errors = []; page.on("pageerror", e => errors.push(String(e))); page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  await page.goto(`http://127.0.0.1:${port}/`);
  step("oldal betölt", (await page.title()).includes("kutatóügynök"), await page.title());
  await page.fill("#key", "probe-token-DUMMY-not-a-secret");
  await page.fill("#q", "Milyen eszközt említenek, és milyen hibákat?");
  await page.fill("#links", "https://www.youtube.com/watch?v=AAAAAAAAAAA");
  await page.fill("#known", "Az AutoDroid egy telefonvezérlő eszköz.");
  await page.click("#go");
  await page.waitForFunction(() => document.getElementById("status").textContent.includes("awaiting_approval"), null, { timeout: 20000 });
  const planTxt = await page.textContent("#plan");
  step("terv megjelenik jóváhagyás előtt", (await page.isVisible("#approve")) && planTxt.includes("plan_hash") && planTxt.includes("known_information"), "plan_hash és known_information látszik");
  const statusBefore = await page.textContent("#status");
  step("jóváhagyás előtt nincs jelentés kártya", (await page.locator("#cards h3").count()) === 0, statusBefore.split("\n")[0]);
  await page.click("#ok");
  await page.waitForFunction(() => document.querySelectorAll("#cards h3").length > 0, null, { timeout: 30000 });
  const st = await page.textContent("#status");
  step("feldolgozás után a státusz végállapot", /completed|partially_completed/.test(st), st.split("\n")[0]);
  const heads = await page.locator("#cards h3").allTextContents();
  step("megtartandó csoport látszik", heads.includes("Megtartandó információk"), heads.join(" | "));
  step("ellenőrizendő nyomok csoport látszik", heads.includes("Ellenőrizendő nyomok"));
  const cards = await page.locator("#cards > div").allTextContents();
  step("eszköz-tétel és hiba-tétel a megtartottak között", cards.some(c => c.includes("AutoDroid")) && cards.some(c => c.includes("elakad")));
  step("a nyom mutatja a konkrét ellenőrzési kérdést", cards.some(c => c.includes("Ellenőrzési kérdés: Megerősíti-e a hivatalos dokumentáció")));
  step("lefedettség látszik", (await page.textContent("#cards")).includes("Lefedettség: 1/1 videó feldolgozva"));
  const links = await page.locator("#cards a").evaluateAll(as => as.map(a => a.href));
  step("forráslink van a kártyákon", links.length > 0 && links.every(h => h.startsWith("https://")), links[0]);
  step("kihagyott részletek összesítve", (await page.textContent("#cards")).includes("Kihagyott részletek"));
  await page.screenshot({ path: `${out}/ui_report.png`, fullPage: true });
  await page.click("#evb");
  await page.waitForFunction(() => !document.getElementById("more").hidden && document.getElementById("more").textContent.includes("Részletes bizonyítékok"), null, { timeout: 10000 });
  const ev = await page.textContent("#more");
  step("bizonyítékok: idézet, szegmens, időbélyeg", ev.includes("idézet [hu]") && ev.includes("szegmensek:") && /\d+:\d\d/.test(ev) && ev.includes("verification_status: not_externally_verified"));
  await page.click("#flb");
  await page.waitForFunction(() => document.getElementById("more").textContent.includes("Szűrési napló"), null, { timeout: 10000 });
  const fl = await page.textContent("#more");
  step("szűrési napló látszik (kihagyott indokkal)", fl.includes("nem releváns") || fl.includes("irrelevant"));
  const btn = page.locator("#cards button", { hasText: "már ismert" }).first();
  await btn.click();
  await page.waitForFunction(() => document.getElementById("cards").textContent.includes("Visszajelzés: már ismert"), null, { timeout: 10000 });
  step("visszajelzés elküldve és megjelenik", true, "„már ismert”, tárolva; modellbetanítás nincs");
  // a tárolt visszajelzés ellenőrzése az API-n át (ugyanazzal a tokennel)
  const jid = (await page.evaluate(() => (typeof jid !== "undefined" ? jid : null)));
  const res = await page.evaluate(async (jobid) => { const r = await fetch("/api/jobs/" + jobid + "/feedback", { headers: { Authorization: "Bearer probe-token-DUMMY-not-a-secret" } }); return r.json(); }, jid);
  step("a visszajelzés az adatbázisban van", Array.isArray(res) && res.length === 1 && res[0].label === "already_known", JSON.stringify(res.map(x => x.label)));
  await page.reload();
  step("oldal frissítés után nem omlik össze", (await page.title()).includes("kutatóügynök"));
  step("nincs böngészőhiba a konzolon", errors.length === 0, errors.join(" | ").slice(0, 200));
  await b.close();
  console.log(log.join("\n")); console.log(fail.length ? `\nEREDMÉNY: ${fail.length} HIBA: ${fail.join("; ")}` : "\nEREDMÉNY: minden lépés rendben");
  process.exit(fail.length ? 1 : 0);
})().catch(e => { console.log(log.join("\n")); console.log("KIVÉTEL:", e.message); process.exit(2); });
